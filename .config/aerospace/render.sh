#!/usr/bin/env bash
# Writes aerospace.toml (gitignored, what AeroSpace reads) from aerospace.toml.in (tracked, edited)
# with the outer gaps of the sketchybar layout. Callers: ../sketchybar/layout.sh (gaps per layout),
# install.sh (first render), .githooks/pre-commit (--check, then re-render).
# Usage: render.sh [LEFT TOP]  gaps as TOML values; default: those in aerospace.toml, else the .in's
#        render.sh --check     exit 1 if aerospace.toml has edits besides the gaps, i.e. it matches
#                              neither the .in nor the committed .in (HEAD) rendered with its gaps
set -euo pipefail

dir="$(cd "$(dirname "$0")" && pwd -P)"
in="$dir/aerospace.toml.in"
out="$dir/aerospace.toml"

gap() { sed -n "s/^gaps\.outer\.$1 = //p" "$2" | head -1; }

# render SOURCE LEFT TOP
render() {
    echo "# GENERATED by render.sh from aerospace.toml.in: edit that file (pre-commit checks this one)"
    awk -v l="$2" -v t="$3" '
        /^gaps\.outer\.left = / { print "gaps.outer.left = " l; next }
        /^gaps\.outer\.top = /  { print "gaps.outer.top = " t; next }
        { print }' "$1"
}

if [[ ${1-} == --check ]]; then
    [[ -f $out ]] || exit 0
    l="$(gap left "$out")" t="$(gap top "$out")"
    diff -q <(render "$in" "$l" "$t") "$out" >/dev/null && exit 0
    if committed="$(git -C "$dir" show HEAD:./aerospace.toml.in 2>/dev/null)"; then
        diff -q <(render <(printf '%s\n' "$committed") "$l" "$t") "$out" >/dev/null && exit 0
    fi
    echo "$out: edits besides the gaps; move them to aerospace.toml.in (diff: rendered .in vs file):" >&2
    diff <(render "$in" "$l" "$t") "$out" >&2 || true
    exit 1
fi

if (($# == 2)); then
    l="$1" t="$2"
else
    l="" t=""
    [[ -f $out ]] && l="$(gap left "$out")" t="$(gap top "$out")"
    l="${l:-$(gap left "$in")}" t="${t:-$(gap top "$in")}"
fi
tmp="$(mktemp "$out.XXXXXX")"
render "$in" "$l" "$t" > "$tmp"
mv "$tmp" "$out"
